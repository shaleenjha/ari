#!/usr/bin/env python3
"""Generates the lock-safe 0033 (app2 E1) and 0034 (app2 E2) files and their rollbacks into pending/. LOCAL tool, no database.
Layout of every generated file (and of 0035, see gen_e3.py):
  * a precheck transaction first (it raises, so nothing after it runs when the target is not in the expected state)
  * then many SHORT transactions, one per table per phase, each with  set local lock_timeout = '5s'; statement_timeout = '60s'
  * the ledger row last, inside a transaction that first verifies every table reached the end state
All of it is plain SQL with explicit begin/commit, so one file = one POST to the Management API query endpoint
(simple query protocol: each commit ends a transaction, an error stops the rest of the request; re-running resumes).
usage: python3 gen_e12.py   (rewrites the four files)"""
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WS = 'f5a1e000-0000-4000-8000-000000000001'
OWNER_UID = 'b14d1605-c766-4684-9a5b-71ffcab6967b'
TABLES = ['account_briefs', 'account_stage_history', 'accounts', 'app_changes', 'app_config', 'app_usage',
          'ari_notes', 'ari_prefs', 'attachments', 'book', 'brief', 'copy_guidance', 'decisions', 'draft_edits', 'draft_tags', 'emails',
          'events', 'gmail_connect_tickets', 'gmail_connection', 'gmail_ingest_runs', 'gmail_oauth_states', 'gmail_shadow_diffs',
          'gmail_shadow_events', 'hygiene_findings', 'log_entries', 'messages', 'notifications', 'ops', 'people', 'plays',
          'push_subscriptions', 'push_tokens', 'queue', 'replies', 'research', 'scan_heartbeat', 'sent_messages', 'sync_state',
          'targets', 'task_events', 'tasks', 'threads']
assert len(TABLES) == 42 and len(set(TABLES)) == 42
BATCH = 1000          # backfill rows per transaction
BATCHES = 2           # backfill transactions per table per run (largest table is about 1,100 rows; a re-run continues)
T = "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '60s';\n"
END = "commit;\n"
ARR = "array['" + "', '".join(TABLES) + "']"


def tx(body):
    return T + body.rstrip('\n') + '\n' + END


def per_table(title, fn):
    return f"\n-- ---------- {title} (one transaction per table) ----------\n" + ''.join(tx(fn(t)) for t in TABLES)


# ------------------------------------------------------------------ 0033 E1 forward
E1_HEAD = f"""-- 0033 app2 E1: tenancy, additive only (migration-map.md section 2, step 1). PENDING: staging first, then prod.
-- GENERATED by test/gen_e12.py; edit the generator, not this file.
-- Needs: 0026 and 0032 (accept_ingest, which lands first) applied; nothing newer than 0035.
-- What it does
--   * schema app with app.workspaces + app.memberships (same shape as app2/db/migrations/0001_tenancy_core.sql)
--   * workspace "Owner" (constant id {WS}) + the owner's membership
--     (user id = the uid public.is_owner() is pinned to since 0024; role sdr)
--   * nullable public.<table>.workspace_id uuid DEFAULT <Owner workspace> on all 42 tenant tables (backup_runs stays platform-side)
-- Why the live app is unaffected
--   * ADD COLUMN with a constant default is metadata-only on PG 11+: no rewrite, existing rows read the default at once.
--   * No policy, grant, function or trigger on public.* changes. Inserts that omit the column get the default.
--   * The only visible change: select=* responses carry one more key (workspace_id). ari_worker_columns() lists it too.
-- Locks: one short transaction per table (ACCESS EXCLUSIVE for the metadata-only ADD COLUMN, milliseconds), each with
--   lock_timeout 5s and statement_timeout 60s, so a busy table makes the request stop cleanly; earlier tables stay done and a
--   re-run (if not exists / on conflict) finishes the rest. The ledger row is written last, only when all 42 columns exist.
-- Run: the whole file as ONE request (Management API query endpoint) or psql -v ON_ERROR_STOP=1 -f. See README.md.
-- Rollback: 0033_app2_e1_tenancy_rollback.sql (same folder)

-- ---------- precheck ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
declare mx text;
begin
  if not exists (select 1 from supabase_migrations.schema_migrations where version = '0026') then
    raise exception '0033 precheck: 0026 (health_alerts) is not applied';
  end if;
  if not exists (select 1 from supabase_migrations.schema_migrations where version = '0032') then
    raise exception '0033 precheck: 0032 (accept_ingest) is not applied; it must land before app2 E1';
  end if;
  select max(version) into mx from supabase_migrations.schema_migrations;
  if mx > '0035' then raise exception '0033 precheck: max(version) is %, expected 0032 (or 0033..0035 on a re-run)', mx; end if;
end $$;
commit;

-- ---------- app schema, types, tables, seed (no lock on any public table) ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
create schema if not exists app;
revoke all on schema app from public;
grant usage on schema app to authenticated;   -- E3 policies call app.is_member(); nothing in app is granted to anon or ari_worker

do $$ begin
  create type app.role_t as enum ('admin','manager','ae','sdr','agent');
exception when duplicate_object then null; end $$;
do $$ begin
  create type app.member_status as enum ('active','invited','revoked');
exception when duplicate_object then null; end $$;

create table if not exists app.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  timezone text not null default 'Asia/Kolkata',
  settings jsonb not null default '{{}}'::jsonb,
  created_at timestamptz not null default now()
);
create table if not exists app.memberships (
  workspace_id uuid not null references app.workspaces(id) on delete cascade,
  user_id uuid not null,
  role app.role_t not null,
  status app.member_status not null default 'active',
  display_name text,
  timezone text,
  created_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);
create index if not exists memberships_user_ws_idx on app.memberships (user_id, workspace_id);
alter table app.workspaces enable row level security;
alter table app.workspaces force row level security;
alter table app.memberships enable row level security;
alter table app.memberships force row level security;
revoke all on app.workspaces, app.memberships from public, anon, authenticated;
grant select on app.workspaces, app.memberships to authenticated;   -- rows visible only once E3 adds the member policies

insert into app.workspaces (id, name) values ('{WS}', 'Owner') on conflict (id) do nothing;
insert into app.memberships (workspace_id, user_id, role, display_name)
values ('{WS}', '{OWNER_UID}', 'sdr', 'Owner')
on conflict (workspace_id, user_id) do nothing;
commit;
"""


def e1_col(t):
    return (f"alter table public.{t} add column if not exists workspace_id uuid default '{WS}'::uuid;\n"
            f"comment on column public.{t}.workspace_id is 'app2 tenancy (0033 E1). Every row belongs to workspace Owner until app2 adds members.';\n")


E1_TAIL = f"""
-- ---------- ledger (only when every table has the column) ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
declare n int;
begin
  select count(*) into n from information_schema.columns
   where table_schema = 'public' and column_name = 'workspace_id' and table_name = any({ARR});
  if n <> 42 then raise exception '0033: % of 42 tables have workspace_id; re-run this file', n; end if;
end $$;
insert into supabase_migrations.schema_migrations(version, name) values ('0033', 'app2_e1_tenancy') on conflict do nothing;
commit;
"""

E1_RB_HEAD = """-- Rollback of 0033 (app2 E1). GENERATED by test/gen_e12.py. Run only after 0035 and 0034 are rolled back.
-- Drops the workspace_id columns (one short transaction per table, ACCESS EXCLUSIVE for a metadata-only DROP COLUMN),
-- then app.workspaces / app.memberships, the two enum types and schema app. Re-runnable: every step is "if exists".
-- Data note: only the workspace_id values (all the Owner constant) and the one workspace + membership row are lost.

-- ---------- precheck: E2 must be rolled back first ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
begin
  if exists (select 1 from supabase_migrations.schema_migrations where version in ('0034', '0035')) then
    raise exception '0033 rollback precheck: 0034/0035 still in the ledger; roll them back first';
  end if;
  if exists (select 1 from pg_trigger where tgname = 'ws_guard' and not tgisinternal) then
    raise exception '0033 rollback precheck: ws_guard triggers still exist; run 0034_app2_e2_backfill_rollback.sql first';
  end if;
end $$;
commit;
"""

E1_RB_TAIL = """
-- ---------- app schema ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
drop table if exists app.memberships;
drop table if exists app.workspaces;
drop type if exists app.member_status;
drop type if exists app.role_t;
do $$ begin
  if exists (select 1 from pg_namespace where nspname = 'app') then
    revoke usage on schema app from authenticated;
  end if;
end $$;
drop schema if exists app;   -- no cascade: fails loudly if anything else was put in app
delete from supabase_migrations.schema_migrations where version = '0033';
commit;
"""

# ------------------------------------------------------------------ 0034 E2 forward
E2_HEAD = f"""-- 0034 app2 E2: backfill + constrain, lock-safe (migration-map.md section 2, step 2). PENDING: staging first, then prod.
-- GENERATED by test/gen_e12.py; edit the generator, not this file. Needs 0033.
-- End state per tenant table (the same 42 as 0033):
--   workspace_id NOT NULL; unique index (workspace_id, <pk>) named <table>_ws_pk_uidx (target for app2 composite FKs in C1);
--   FK <table>_workspace_fk -> app.workspaces(id), validated; trigger ws_guard (app.ws_guard()).
-- Phases, each ONE SHORT TRANSACTION PER TABLE with lock_timeout 5s + statement_timeout 60s (phase-major: every table
-- finishes a phase before the next phase starts):
--   A guard     create trigger ws_guard if missing (no drop/re-create). From here a NULL workspace_id on INSERT becomes Owner,
--               so no new null rows can appear while the rest runs.
--   B backfill  rows still null (expected 0) get Owner, at most {BATCH} rows per transaction, {BATCHES} transactions per table per run,
--               with session_replication_role = replica set only when nulls exist (touch_row must not bump updated_at/field_ts,
--               ws_guard must not refuse the fill). Explicit ROW EXCLUSIVE lock first: no lock upgrade. After the batches one read-only
--               check transaction stops the request (batches already committed) if nulls remain: re-run the file.
--   C constrain add CHECK (workspace_id is not null) NOT VALID (<table>_ws_nn) and the FK NOT VALID: catalog only, no scan.
--   D validate  VALIDATE both: SHARE UPDATE EXCLUSIVE, reads and writes keep flowing during the scan.
--   E not null  SET NOT NULL (PG 12+ uses the validated check, no scan), then drop the helper check.
--   F index     plain CREATE UNIQUE INDEX IF NOT EXISTS (SHARE: blocks writes on that one table for the build, tables are
--               small, about 1,100 rows max; CONCURRENTLY deliberately not used).
--   ledger      written last, only when all 42 tables are in the end state.
-- Live app: no policy, grant or function on public.* changes. Inserts from the app and from ari_worker omit the column
-- and get the default; the guard is SECURITY DEFINER with an empty search_path, so ari_worker needs no rights on app.
-- Restore note: a pre-0033 backup restored with session_replication_role = replica skips ws_guard, so the restore
-- must fill workspace_id (or restore before this step). See README.md.
-- Run: the whole file as ONE request (Management API query endpoint) or psql -v ON_ERROR_STOP=1 -f. Re-runnable.
-- Rollback: 0034_app2_e2_backfill_rollback.sql (same folder)

-- ---------- precheck ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
declare n int;
begin
  if not exists (select 1 from supabase_migrations.schema_migrations where version = '0033') then
    raise exception '0034 precheck: 0033 (app2 E1) is not applied';
  end if;
  select count(*) into n from information_schema.columns
   where table_schema = 'public' and column_name = 'workspace_id' and table_name = any({ARR});
  if n <> 42 then raise exception '0034 precheck: % of 42 tables have workspace_id', n; end if;
  if not exists (select 1 from app.workspaces where id = '{WS}') then raise exception '0034 precheck: workspace Owner missing'; end if;
end $$;
commit;

-- ---------- guard function (no lock on any public table) ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
create or replace function app.ws_guard() returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    new.workspace_id := coalesce(new.workspace_id, '{WS}'::uuid);
    return new;
  end if;
  if new.workspace_id is distinct from old.workspace_id then
    raise exception 'workspace_id cannot change (% row)', tg_table_name using errcode = '42501';
  end if;
  return new;
end $$;
revoke all on function app.ws_guard() from public, anon, authenticated;
commit;
"""


def e2_guard(t):
    return f"""do $$ begin
  if not exists (select 1 from pg_trigger where tgname = 'ws_guard' and tgrelid = 'public.{t}'::regclass) then
    create trigger ws_guard before insert or update of workspace_id on public.{t} for each row execute function app.ws_guard();
  end if;
end $$;
"""


def e2_backfill(t):
    return f"""lock table public.{t} in row exclusive mode;
do $$
declare n int;
begin
  if exists (select 1 from public.{t} where workspace_id is null) then
    perform set_config('session_replication_role', 'replica', true);
    update public.{t} set workspace_id = '{WS}'::uuid
     where ctid = any (array(select ctid from public.{t} where workspace_id is null limit {BATCH}));
    get diagnostics n = row_count;
    perform set_config('session_replication_role', 'origin', true);
    raise notice '0034: backfilled % row(s) in {t}', n;
  end if;
end $$;
"""


E2_BACKFILL_CHECK = f"""
-- ---------- B check: stop (keeping the batches above) if any null is left; re-running the file continues the backfill ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
declare t text; has_null boolean; left_ text := '';
begin
  foreach t in array {ARR} loop
    execute format('select exists (select 1 from public.%I where workspace_id is null)', t) into has_null;
    if has_null then left_ := left_ || ' ' || t; end if;
  end loop;
  if left_ <> '' then raise exception '0034: null workspace_id still left in:%; re-run this file to continue the backfill', left_; end if;
end $$;
commit;
"""


def e2_constrain(t):
    return f"""do $$ begin
  if not exists (select 1 from pg_attribute where attrelid = 'public.{t}'::regclass and attname = 'workspace_id' and attnotnull)
     and not exists (select 1 from pg_constraint where conrelid = 'public.{t}'::regclass and conname = '{t}_ws_nn') then
    alter table public.{t} add constraint {t}_ws_nn check (workspace_id is not null) not valid;
  end if;
  if not exists (select 1 from pg_constraint where conrelid = 'public.{t}'::regclass and conname = '{t}_workspace_fk') then
    alter table public.{t} add constraint {t}_workspace_fk foreign key (workspace_id) references app.workspaces(id) not valid;
  end if;
end $$;
"""


def e2_validate(t):
    return f"""do $$ begin
  if exists (select 1 from pg_constraint where conrelid = 'public.{t}'::regclass and conname = '{t}_ws_nn' and not convalidated) then
    alter table public.{t} validate constraint {t}_ws_nn;
  end if;
  if exists (select 1 from pg_constraint where conrelid = 'public.{t}'::regclass and conname = '{t}_workspace_fk' and not convalidated) then
    alter table public.{t} validate constraint {t}_workspace_fk;
  end if;
end $$;
"""


def e2_notnull(t):
    return f"""do $$ begin
  if not exists (select 1 from pg_attribute where attrelid = 'public.{t}'::regclass and attname = 'workspace_id' and attnotnull) then
    alter table public.{t} alter column workspace_id set not null;   -- proven by the validated {t}_ws_nn: no scan
  end if;
  if exists (select 1 from pg_constraint where conrelid = 'public.{t}'::regclass and conname = '{t}_ws_nn') then
    alter table public.{t} drop constraint {t}_ws_nn;
  end if;
end $$;
"""


def e2_index(t):
    return f"""do $$
declare pk text;
begin
  if to_regclass('public.{t}_ws_pk_uidx') is null then
    select string_agg(format('%I', a.attname), ', ' order by k.ord) into pk
      from pg_index i
      cross join lateral unnest(i.indkey) with ordinality k(attnum, ord)
      join pg_attribute a on a.attrelid = i.indrelid and a.attnum = k.attnum
     where i.indrelid = 'public.{t}'::regclass and i.indisprimary;
    if pk is null then raise exception '0034: public.{t} has no primary key'; end if;
    execute format('create unique index if not exists {t}_ws_pk_uidx on public.{t} (workspace_id, %s)', pk);
  end if;
end $$;
"""


E2_TAIL = f"""
-- ---------- ledger (only when every table is in the end state) ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
declare t text; bad text := '';
begin
  foreach t in array {ARR} loop
    if not exists (select 1 from pg_attribute where attrelid = format('public.%I', t)::regclass and attname = 'workspace_id' and attnotnull)
       or to_regclass(format('public.%I', t || '_ws_pk_uidx')) is null
       or not exists (select 1 from pg_constraint where conrelid = format('public.%I', t)::regclass and conname = t || '_workspace_fk' and convalidated)
       or exists (select 1 from pg_constraint where conrelid = format('public.%I', t)::regclass and conname = t || '_ws_nn')
       or not exists (select 1 from pg_trigger where tgname = 'ws_guard' and tgrelid = format('public.%I', t)::regclass) then
      bad := bad || ' ' || t;
    end if;
  end loop;
  if bad <> '' then raise exception '0034: not finished on:%; re-run this file', bad; end if;
end $$;
insert into supabase_migrations.schema_migrations(version, name) values ('0034', 'app2_e2_backfill') on conflict do nothing;
commit;
"""

E2_RB_HEAD = """-- Rollback of 0034 (app2 E2). GENERATED by test/gen_e12.py. Run after 0035 is rolled back. Leaves 0033 in place
-- (nullable workspace_id with default). One short transaction per table (ACCESS EXCLUSIVE, catalog-only work), re-runnable.

-- ---------- precheck: E3 must be rolled back first ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
begin
  if exists (select 1 from supabase_migrations.schema_migrations where version = '0035') then
    raise exception '0034 rollback precheck: 0035 still in the ledger; run 0035_app2_e3_dual_rls_rollback.sql first';
  end if;
end $$;
commit;
"""


def e2_rb(t):
    return (f"drop trigger if exists ws_guard on public.{t};\n"
            f"alter table public.{t} drop constraint if exists {t}_workspace_fk;\n"
            f"alter table public.{t} drop constraint if exists {t}_ws_nn;\n"
            f"drop index if exists public.{t}_ws_pk_uidx;\n"
            f"alter table public.{t} alter column workspace_id drop not null;\n")


E2_RB_TAIL = """
-- ---------- guard function + ledger ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
drop function if exists app.ws_guard();
delete from supabase_migrations.schema_migrations where version = '0034';
commit;
"""


def write(name, text):
    with open(os.path.join(HERE, name), 'w') as f:
        f.write(text)
    print('wrote', name, text.count('\nbegin;') + text.startswith('begin;'), 'transactions')


if __name__ == '__main__':
    write('0033_app2_e1_tenancy.sql', E1_HEAD + per_table('add workspace_id', e1_col) + E1_TAIL)
    write('0033_app2_e1_tenancy_rollback.sql', E1_RB_HEAD + per_table('drop workspace_id', lambda t: f"alter table public.{t} drop column if exists workspace_id;\n") + E1_RB_TAIL)
    e2 = E2_HEAD + per_table('A guard trigger', e2_guard)
    for b in range(BATCHES):
        e2 += per_table(f'B backfill batch {b + 1} of {BATCHES} (at most {BATCH} rows each)', e2_backfill)
    e2 += E2_BACKFILL_CHECK
    e2 += (per_table('C constraints NOT VALID', e2_constrain) + per_table('D validate', e2_validate)
           + per_table('E set not null, drop helper check', e2_notnull) + per_table('F unique (workspace_id, pk) index', e2_index) + E2_TAIL)
    write('0034_app2_e2_backfill.sql', e2)
    write('0034_app2_e2_backfill_rollback.sql', E2_RB_HEAD + per_table('undo E2', e2_rb) + E2_RB_TAIL)
