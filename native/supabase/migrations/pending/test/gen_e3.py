#!/usr/bin/env python3
"""Generates 0035_app2_e3_dual_rls.sql and its rollback from the policies of a local prod-shape database
(baseline + 0015..0032, BEFORE 0033..0035 are applied to it).
Every owner policy (TO authenticated, using public.is_owner()) on one of the 42 tenant tables (gen_e12.TABLES, the tables that
get workspace_id in 0033) gets `OR (select app.is_member(workspace_id))`; owner policies on other tables (0032 added
gmail_events and scan_runs, which have no workspace_id) are left exactly as they are. The rollback holds the exact previous
definitions. ari_worker policies are not touched. One short transaction per table: drop + create of that table's policies
together, so no table is ever without its policy.
Local only: PGHOST/PGPORT/PGUSER. usage: gen_e3.py <db>"""
import json, subprocess, sys, os
from itertools import groupby
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_e12 import TABLES

DB = sys.argv[1] if len(sys.argv) > 1 else 'prodshape'
q = """select json_agg(json_build_object('t', c.relname, 'n', p.polname, 'cmd', p.polcmd, 'perm', p.polpermissive,
  'roles', (select array_agg(rolname order by rolname) from pg_roles where oid = any(p.polroles)),
  'using', pg_get_expr(p.polqual, p.polrelid), 'check', pg_get_expr(p.polwithcheck, p.polrelid)) order by c.relname, p.polname)
from pg_policy p join pg_class c on c.oid = p.polrelid where c.relnamespace = 'public'::regnamespace"""
rows = json.loads(subprocess.run(['psql', '-At', '-d', DB, '-c', q], capture_output=True, text=True, check=True,
                                 env={**os.environ, 'PGOPTIONS': '-c search_path='}).stdout)
assert not any('app.is_member' in ((r['using'] or '') + (r['check'] or '')) for r in rows), 'database already has E3 applied'
CMD = {'r': 'select', 'a': 'insert', 'w': 'update', 'd': 'delete', '*': 'all'}


def create(r, using, check):
    s = f"create policy {r['n']} on public.{r['t']} as {'permissive' if r['perm'] else 'restrictive'} for {CMD[r['cmd']]} to {', '.join(r['roles'])}"
    if using: s += f"\n  using ({using})"
    if check: s += f"\n  with check ({check})"
    return s + ';'


DUAL = lambda e: f"({e}) or (select app.is_member(workspace_id))" if e else e
owner_all = [r for r in rows if r['roles'] == ['authenticated'] and 'is_owner()' in ((r['using'] or '') + (r['check'] or ''))]
owner = [r for r in owner_all if r['t'] in TABLES]
owner_only = [r for r in owner_all if r['t'] not in TABLES]
other = [r for r in rows if r not in owner_all]
assert all(r['roles'] == ['ari_worker'] for r in other), other
N, NALL, W = len(owner), len(owner_all), len(other)
NT = len({r['t'] for r in owner})
OWNT = ', '.join(sorted({r['t'] for r in owner_only})) or 'none'
ARR = "array['" + "', '".join(TABLES) + "']"
TX = "begin;\nset local lock_timeout = '5s';\nset local statement_timeout = '60s';\n"


def per_table(make):
    out = []
    for t, grp in groupby(owner, key=lambda r: r['t']):
        out.append(TX + '\n'.join(f"drop policy if exists {r['n']} on public.{t};\n" + make(r) for r in grp) + '\ncommit;')
    return '\n'.join(out)


here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEAD = (open(os.path.join(here, 'test', 'e3_head.sql')).read()
        .replace('{NALL}', str(NALL)).replace('{N}', str(N)).replace('{TN}', str(NT)).replace('{W}', str(W))
        .replace('{OWNT}', OWNT).replace('{NOWN}', str(len(owner_only))).replace('{ARR}', ARR))
LEDGER = f"""
-- ---------- ledger (only when every owner policy on a tenant table carries the member clause) ----------
begin;
set local lock_timeout = '5s';
set local statement_timeout = '60s';
do $$
declare n int;
begin
  select count(*) into n from pg_policies where schemaname = 'public' and roles = '{{authenticated}}' and tablename = any({ARR})
    and (coalesce(qual, '') || coalesce(with_check, '')) like '%is_owner()%'
    and ((qual is not null and qual not like '%app.is_member(%workspace_id)%')
      or (with_check is not null and with_check not like '%app.is_member(%workspace_id)%'));
  if n <> 0 then raise exception '0035: % owner policies still without the member clause; re-run this file', n; end if;
end $$;
insert into supabase_migrations.schema_migrations(version, name) values ('0035', 'app2_e3_dual_rls') on conflict do nothing;
commit;
"""
with open(os.path.join(here, '0035_app2_e3_dual_rls.sql'), 'w') as f:
    f.write(HEAD)
    f.write(f'\n-- ---------- owner policies, now dual ({N} policies on {NT} tables; one transaction per table) ----------\n')
    f.write(per_table(lambda r: create(r, DUAL(r['using']), DUAL(r['check']))))
    f.write('\n' + LEDGER)
with open(os.path.join(here, '0035_app2_e3_dual_rls_rollback.sql'), 'w') as f:
    f.write(f"-- Rollback of 0035 (app E3). GENERATED by test/gen_e3.py. Restores the {N} owner policies exactly as they were before\n"
            "-- (verbatim pg_get_expr), one short transaction per table (drop + create together), then drops the app.* member\n"
            "-- policies and the helpers. ari_worker policies and the owner-only policies were never touched. Re-runnable.\n\n")
    f.write(f'-- ---------- owner policies, restored ({NT} tables) ----------\n')
    f.write(per_table(lambda r: create(r, r['using'], r['check'])))
    f.write("\n\n-- ---------- app.* policies, helpers, ledger ----------\n" + TX +
            "do $$ begin\n"
            "  if to_regclass('app.workspaces') is not null then drop policy if exists ws_read on app.workspaces; end if;\n"
            "  if to_regclass('app.memberships') is not null then drop policy if exists own_or_ws_read on app.memberships; end if;\n"
            "  if to_regtype('app.role_t') is not null then drop function if exists app.has_role(uuid, app.role_t[]); end if;\n"
            "end $$;\n"
            "drop function if exists app.is_member(uuid);\n"
            "delete from supabase_migrations.schema_migrations where version = '0035';\ncommit;\n")
print(f'owner policies made dual: {N} on {NT} tables; owner-only policies left as they are: {len(owner_only)} ({OWNT}); '
      f'ari_worker policies untouched: {W}')
