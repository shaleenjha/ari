"""Outbound daily report v2 (Oct 16 2026): short, numbers first. Sent by Hark from owner@example.com via gws.
Previous version: scripts/daily_report_v1.py.

Reads the Ari reporting layer in Supabase (report_summary / accounts_worked, migration 0009); falls back to the
Google Sheet when Supabase is unreachable. The reporting day is YESTERDAY (IST): the report runs at 06:05 IST.
"Week" = Mon-Sun IST week containing yesterday, "month" = calendar month containing yesterday (both to date).

Machine contract (Wren parses it, keep it stable):
  sender owner@example.com · subject "Outbound daily report · YYYY-MM-DD" (IST send date) ·
  body contains "Generated by Hark" (the scheduled task's send-once check) ·
  headings "3. HARK SUGGESTS (Owner approves each)" with one card per line ("N) ...") and "4. TOMORROW"
  whose first line is "- N LinkedIn actions due.".
  (v18.9, Oct 17: the exec-track list is no longer in this report; scripts/exec_track_handoff.py emails it separately.)

Usage: python3 scripts/daily_report.py [--send] [--out FILE] [--source sheet]
Run with google credentials for owner@example.com (the Supabase service binding is injected by the proxy).
"""
