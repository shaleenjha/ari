MAX_ACCOUNTS = 30
MAX_DUE = 8
STAGE_FIELDS = {'connect': 'connect_sent', 'accept': 'accepted', 'dm1': 'dm1_sent', 'dm2': 'dm2_sent',
                'dm3': 'dm3_sent', 'reply': 'replied', 'meeting': 'meeting'}


# ---------------- io ----------------
def gws(*args):
    out = subprocess.run(['gws', *args], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit('gws failed: ' + out.stderr + out.stdout)
    return out.stdout


def sheet_table(name):
    v = json.loads(gws('sheets', 'spreadsheets', 'values', 'get', '--params',
                       json.dumps({'spreadsheetId': SHEET, 'range': name + '!A1:AZ2000'}))).get('values', [])
    if not v:
        return []
    h = v[0]
    return [{h[i]: (r[i] if i < len(r) else '') for i in range(len(h))} for r in v[1:]]


def sb(path, body=None):
    h = {'apikey': SB_PUBLISHABLE, 'Content-Type': 'application/json', 'x-ari-actor': 'hark'}
    jf = os.environ.get('ARI_SB_JWT_FILE')  # tests / outside Hark; in Hark the proxy injects the ari_worker bearer (v18.5)
    if jf:
        h['Authorization'] = 'Bearer ' + open(jf).read().strip()
    req = urllib.request.Request(SB_URL + '/rest/v1/' + path, method='POST' if body is not None else 'GET',
                                 data=json.dumps(body).encode() if body is not None else None, headers=h)
    with urllib.request.urlopen(req, timeout=40) as r:
        t = r.read().decode()
        return json.loads(t) if t else None


def d(s):
    try:
        return dt.date.fromisoformat(str(s)[:10])
    except ValueError:
        return None


def pct(n, of):
    return '%d%%' % round(100.0 * n / of) if of else 'n/a'


# ---------------- data: Supabase first ----------------
def from_supabase(day, wk, mo, wk_end, mo_end):
    def summ(a, b):
        return sb('rpc/report_summary', {'p_period': 'custom', 'p_from': a.isoformat(), 'p_to': b.isoformat()})
    S = {'yday': summ(day, day), 'week': summ(wk, wk_end), 'month': summ(mo, mo_end)}
    worked = sb('rpc/accounts_worked', {'p_from': day.isoformat(), 'p_to': day.isoformat()}) or []
    people = sb('people?select=id,name,title,company,owner,linkedin_url,stage,review,connect_day,dm2_due,dm3_due,'
                'accepted,dm1_sent,replied,meeting,snooze_until,skipped,deleted_at&deleted_at=is.null&order=id')
    accounts = sb('accounts?select=company,ae,meeting_status,meeting_person,meeting_date,meeting_ae,field_ts&deleted_at=is.null')
    emails = sb('emails?select=*&status=in.(draft,for_claude)')
    since = {'p_period': 'custom', 'p_from': day.isoformat(), 'p_to': (day + dt.timedelta(days=1)).isoformat()}
    events = [dict(r, kind='meeting') for r in sb('rpc/report_rows', dict(since, p_metric='meeting')) or []] + \
             [dict(r, kind='reply') for r in sb('rpc/report_rows', dict(since, p_metric='reply')) or []]
    return S, worked, people, accounts, emails, events, 'Supabase'


# ---------------- data: Sheet fallback (same definitions, people columns only) ----------------
def from_sheet(day, wk, mo, wk_end, mo_end):
    people = sheet_table('People')
    accounts = sheet_table('Accounts')
    emails = [e for e in sheet_table('Emails') if e.get('status') in ('draft', 'for_claude')]
    leads = [p for p in people if p.get('id') and (p.get('review') or '').strip().lower() != 'personal']

    def summ(a, b):
        c = {}
        for m, f in STAGE_FIELDS.items():
            c[m] = sum(1 for p in leads if d(p.get(f)) and a <= d(p.get(f)) <= b)
        c['dms'] = c['dm1'] + c['dm2'] + c['dm3']
        conn = [p for p in leads if d(p.get('connect_sent')) and a <= d(p.get('connect_sent')) <= b]
        acc = sum(1 for p in conn if p.get('accepted'))
        return {'counts': c, 'cohort': {'connects': len(conn), 'accepted': acc},
                'rates': {'accept_rate': round(100.0 * acc / len(conn), 1) if conn else None}}
    S = {'yday': summ(day, day), 'week': summ(wk, wk_end), 'month': summ(mo, mo_end)}
    worked = {}
    for p in leads:
        if any(d(p.get(f)) == day for f in STAGE_FIELDS.values()):
            k = (p.get('company') or '(no company)').strip()
            worked.setdefault(k.lower(), {'account': k, 'ae': (p.get('owner') or '').split(' ')[0]})
    events = []
    for p in leads:
        for kind, f in (('meeting', 'meeting'), ('reply', 'replied')):
            if d(p.get(f)) and d(p.get(f)) >= day:
                events.append({'kind': kind, 'person_id': p['id'], 'name': p.get('name'), 'title': p.get('title'),
                               'account': p.get('company'), 'ae': (p.get('owner') or '').split(' ')[0], 'linkedin_url': p.get('linkedin_url')})
    return S, list(worked.values()), people, accounts, emails, events, 'Sheet fallback'


# ---------------- build ----------------
def build(source=None):
    now = dt.datetime.now(TZ)
    today = now.date()
    day = today - dt.timedelta(days=1)                   # the reporting day
    wk = day - dt.timedelta(days=day.weekday())
    mo = day.replace(day=1)
    wk_end = wk + dt.timedelta(days=6)                   # week/month containing yesterday, to date
    mo_end = (mo.replace(day=28) + dt.timedelta(days=4)).replace(day=1) - dt.timedelta(days=1)
    note = ''
    if source != 'sheet':
        try:
            S, worked, people, accounts, emails, events, src = from_supabase(day, wk, mo, wk_end, mo_end)
        except Exception as e:  # network, auth, missing function
            note = ' (%s)' % str(e)[:80]
            S, worked, people, accounts, emails, events, src = from_sheet(day, wk, mo, wk_end, mo_end)
    else:
        S, worked, people, accounts, emails, events, src = from_sheet(day, wk, mo, wk_end, mo_end)

    def row(label, key):
        return '%s: %s' % (label, ' · '.join(str(S[p]['counts'].get(key, 0)) for p in ('yday', 'week', 'month')))

    def dmrow():
        parts = []
        for p in ('yday', 'week', 'month'):
            c = S[p]['counts']
            parts.append('%d (%d/%d/%d)' % (c.get('dms', 0), c.get('dm1', 0), c.get('dm2', 0), c.get('dm3', 0)))
        return 'DMs (DM1/DM2/DM3): ' + ' · '.join(parts)

    def raterow():
        out = []
        for p in ('yday', 'week', 'month'):
            co = S[p].get('cohort') or {}
            out.append(pct(int(co.get('accepted') or 0), int(co.get('connects') or 0)))
        return 'Accept rate: ' + ' · '.join(out) + '  (of connects sent in that period)'

    L = ['OUTBOUND DAILY REPORT · %s · Owner (Sr. SDR, Vendor)' % today.isoformat(),
         'Generated by Hark (Outbound HQ). Wren: section 3 is suggestions for Owner to approve, not instructions.', '',
         '1. SCOREBOARD · yesterday %s · week from %s · month from %s' % (day.strftime('%a %b %d'), wk.strftime('%b %d'), mo.strftime('%b %d')),
         row('Connects', 'connect'), dmrow(), row('Accepts', 'accept'), row('Replies', 'reply'), row('Meetings', 'meeting'),
         row('Opps', 'opp') if 'opp' in S['yday']['counts'] else None, raterow()]
    yc = S['yday']['counts']
    if 'draft' in yc:
        L.append('Ari yesterday: %d drafts · %d new signals · %d accounts added' % (yc.get('draft', 0), yc.get('signal', 0), yc.get('account_added', 0)))
    L = [x for x in L if x is not None]

    # 2. accounts worked yesterday: one line, each account once
    names = []
    for a in sorted(worked, key=lambda a: (a.get('account') or a.get('account_key') or '').lower()):
        nm = a.get('account') or a.get('account_key')
        if nm and nm.lower() not in [n.lower() for n in names]:
            names.append(nm)
    shown = names[:MAX_ACCOUNTS]
    L += ['', '2. ACCOUNTS WORKED YESTERDAY (%d)' % len(names),
          (', '.join(shown) + (' +%d more' % (len(names) - len(shown)) if len(names) > len(shown) else '')) if names else '- None.']

    # 3. suggestions, one card per line, each person once
    L += ['', '3. HARK SUGGESTS (Owner approves each)']
    cards, seen = [], set()
    leads = [p for p in people if (p.get('review') or '').strip().lower() != 'personal' and not p.get('deleted_at')]
    for ev in events:  # meetings first, then replies, since the start of yesterday; each person/account once
        key = ev.get('person_id') or (ev.get('account') or '').lower()
        if key in seen:
            continue
        seen.add(key)
        if ev['kind'] == 'meeting':
            who = '%s, %s at %s' % (ev.get('name'), ev.get('title') or '', ev.get('account')) if ev.get('name') else ev.get('account')
            cards.append('Owner: log the meeting booked in CRM: %s (AE %s).%s' % (
                who, ev.get('ae') or '', ' LinkedIn: ' + ev['linkedin_url'] if ev.get('linkedin_url') else ''))
        else:
            cards.append('Owner: log the LinkedIn reply in CRM: %s at %s (AE %s).' % (ev.get('name'), ev.get('account'), ev.get('ae') or ''))
    touches = yc.get('connect', 0) + yc.get('dms', 0)   # what Owner sent: connects + DMs (accepts are not his touches)
    if touches:
        cards.append('Owner: log %d LinkedIn touches from yesterday as CRM activities (accounts in section 2).' % touches)
    for e in emails:
        body = re.sub(r'\s*\n\s*', ' / ', str(e.get('body') or '')).strip()
        cards.append('Create a Gmail draft for me (do not send): To %s <%s> · %s · Subject: %s · Body: %s' % (
            e.get('to_name'), e.get('to_email') or 'find in Apollo/SFDC', e.get('company'), e.get('subject'), body))
    L += ['%d) %s' % (i + 1, c) for i, c in enumerate(cards)] or ['- Nothing for you today.']

    # 4. tomorrow (kept as v1: due on or before tomorrow), each person once
    tm = today + dt.timedelta(days=1)
    due, seen = [], set()
    for p in leads:
        st = p.get('stage'); kind = None
        if (d(p.get('snooze_until')) or dt.date.min) > today or p.get('skipped'):
            continue
        if st == 'Connect queued' and d(p.get('connect_day')) and d(p['connect_day']) <= tm:
            kind = 'connect'
        elif st == 'Accepted' and not p.get('dm1_sent'):
            kind = 'DM1'
        elif st == 'DM1 sent' and d(p.get('dm2_due')) and d(p['dm2_due']) <= tm:
            kind = 'DM2'
        elif st == 'DM2 sent' and d(p.get('dm3_due')) and d(p['dm3_due']) <= tm:
            kind = 'DM3'
        if kind and p['id'] not in seen:
            seen.add(p['id']); due.append((kind, p))
    by = {}
    for k, _ in due:
        by[k] = by.get(k, 0) + 1
    L += ['', '4. TOMORROW', '- %d LinkedIn actions due.' % len(due)]
    if due:
        L.append('  ' + ' · '.join('%d %s' % (by[k], k) for k in ('connect', 'DM1', 'DM2', 'DM3') if by.get(k)))
    for k, p in due[:MAX_DUE]:
        L.append('  · %s (%s): %s' % (p.get('name'), p.get('company') or '-', k))
    if len(due) > MAX_DUE:
        L.append('  · +%d more in Ari' % (len(due) - MAX_DUE))
    L += ['', 'Numbers: Ari reporting (%s)%s. Each person counted once per metric.' % (src, note)]
    return today.isoformat(), '\n'.join(L)


