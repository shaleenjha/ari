#!/usr/bin/env python3
"""Exec track end-of-day handoff (Ari v18.9, Oct 17 2026).

People Owner sends to the exec track in Ari (stored as stage 'Founder' / route 'Founder via Aide') queue up. Once a day, after
his US day ends (~06:05 IST, right after the daily report), this emails his WORK inbox (work@example.com, read by his
work Claude "Wren") one message with paste-ready Slack text: Wren posts the parent message in Slack
#ae-founder-linkedin-requests and the numbered list as a thread reply. Hark itself never messages Slack, LinkedIn or anyone else.

Rules:
- Only people whose LinkedIn connection note (people.dm, Sheet K dm) is drafted go out; the rest roll to the next day.
- Never twice: a person is handed off once (Queue row action 'Brief Aide', any status, marks them handed off; the same row
  the old copy flow wrote, and what daily_report.for_aide used to treat as briefed). Never two emails on one IST day
  (Gmail sent is checked for today's subject before sending).
- No email at all when nobody is ready.
- Left out: personal, Hold/customer/closed accounts, people whose why starts "On hold", stage Hold, notes that fail the
  style gates (over 300 characters, em/en dashes).
Subject "Exec track requests · YYYY-MM-DD" (IST date, middle dot), from owner@example.com.

Usage: python3 scripts/exec_track_handoff.py            (dry run: prints the email, sends and writes nothing)
       python3 scripts/exec_track_handoff.py --send     (needs shell credentials google owner@example.com)
Supabase is read/written as the restricted worker role (proxy-injected bearer, same as scripts/daily_report.py sb()).
"""
import json, re, subprocess, sys, urllib.error, datetime as dt
from zoneinfo import ZoneInfo
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from daily_report import sb  # restricted worker-key REST helper

TO = 'work@example.com'
TZ = ZoneInfo('Asia/Kolkata')
CHANNEL = '#ae-founder-linkedin-requests'
MAX_PER_DAY = 20
DONE_ACTION = 'Brief Aide'          # stored queue action meaning "handed off" (display maps it to "Exec track handoff")
SUBJECT = 'Exec track requests · %s'
INSTRUCTION = ('Generated by Hark. Claude: post this as a new message in Slack %s, then the numbered list as a thread '
               'reply, exactly as written.' % CHANNEL)
PARENT = ("Hey @Aide, can you please send these connection requests from Founder's LinkedIn with the notes below? Thanks!")
HOLD_ACCOUNT_STAGES = ('Hold', 'Customer', 'Closed lost', 'Not a fit')


def gws(*args):
    out = subprocess.run(['gws', *args], capture_output=True, text=True)
    if out.returncode != 0:
        raise SystemExit('gws failed: ' + (out.stderr or out.stdout)[:400])
    return out.stdout


def li_short(u):
    u = str(u or '').strip()
    u = re.sub(r'^https?://', '', u, flags=re.I)
    u = re.sub(r'^(www\.|[a-z]{2}\.)(?=linkedin\.com)', '', u, flags=re.I)
    u = u.split('?')[0].split('#')[0].rstrip('/')
    return u


def clean_title(t):
    t = re.sub(r'\s*\((formerly|previously|ex|leads|led|also)\b[^)]*\)', '', str(t or '').strip(), flags=re.I).strip()  # drop "(formerly CPO)" asides
    return t or '-'


def note_ok(n):
    n = str(n or '').strip()
    if not n:
        return 'no note yet'
    if len(n) > 300:
        return 'note over 300 characters'
    if re.search('[\u2013\u2014\u2012]', n):
        return 'note has a dash'
    return ''


def candidates():
    rows = sb('people?select=id,name,title,company,owner,linkedin_url,stage,route,lane,dm,review,why_this_person'
              '&deleted_at=is.null&or=(stage.eq.Founder,lane.eq.founder,route.ilike.*founder*)&order=company,id') or []
    done = {q.get('target') for q in (sb('queue?select=target&action=eq.' + DONE_ACTION.replace(' ', '%20')) or [])}
    hold = {(a.get('company') or '').lower() for a in (sb('accounts?select=company,stage&deleted_at=is.null') or [])
            if (a.get('stage') or '') in HOLD_ACCOUNT_STAGES}
    keep = []
    for p in rows:
        if p['id'] in done or (p.get('review') or '') == 'personal' or (p.get('stage') or '') == 'Hold':
            continue
        if (p.get('company') or '').lower() in hold or str(p.get('why_this_person') or '').lower().startswith('on hold'):
            continue
        if not re.search('founder', '%s %s' % (p.get('stage') or '', p.get('route') or ''), re.I):
            continue   # lane-only leftovers that were taken back to Owner's lane
        keep.append(p)
    ready, waiting = [], []
    for p in keep:
        why = note_ok(p.get('dm')) or ('' if p.get('linkedin_url') else 'no LinkedIn URL')
        (waiting if why else ready).append((p, why))
    return [p for p, _ in ready][:MAX_PER_DAY], waiting + [(p, 'over today\'s cap') for p, _ in ready[MAX_PER_DAY:]]


def body_for(ready):
    L = [INSTRUCTION, '', 'MESSAGE:', PARENT, '', 'THREAD REPLY:']
    for i, p in enumerate(ready, 1):
        L.append('%d. %s, %s, %s' % (i, p.get('name'), clean_title(p.get('title')), p.get('company') or '-'))
        L.append(li_short(p.get('linkedin_url')))
        L += ['> ' + ln for ln in str(p['dm']).strip().splitlines() if ln.strip()]
        L.append('')
    return '\n'.join(L).rstrip() + '\n'


def sent_today(subject):
    q = 'in:sent to:%s subject:"Exec track requests" newer_than:2d' % TO
    lst = json.loads(gws('gmail', 'users', 'messages', 'list', '--params', json.dumps({'userId': 'me', 'q': q, 'maxResults': 20})) or '{}')
    for m in lst.get('messages', []) or []:
        g = json.loads(gws('gmail', 'users', 'messages', 'get', '--params', json.dumps(
            {'userId': 'me', 'id': m['id'], 'format': 'metadata', 'metadataHeaders': ['Subject']})))
        for h in g.get('payload', {}).get('headers', []):
            if h.get('name', '').lower() == 'subject' and h.get('value', '').strip() == subject:
                return True
    return False


LEDGER = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'work', 'exec_track', 'ledger.json')


def ledger(day=None, ids=None):
    try:
        d = json.load(open(LEDGER))
    except (OSError, ValueError):
        d = {}
    if day is not None and ids is not None:
        d[day] = ids
        os.makedirs(os.path.dirname(LEDGER), exist_ok=True)
        json.dump(d, open(LEDGER, 'w'), indent=1)
    return d


def post_once(path, row):
    try:
        sb(path, row)
    except urllib.error.HTTPError as e:
        if e.code != 409:   # 409 = this person's handoff row already exists (id is per person)
            raise


def mark(ready, day):
    for p in ready:
        post_once('queue', {'id': 'QH-' + p['id'], 'action': DONE_ACTION, 'target': p['id'], 'status': 'done',
                     'details': '%s (%s). Exec track handoff, end of day %s. Nothing sent by Ari to anyone but Owner\'s work inbox.' % (p.get('name'), p.get('company') or '', day),
                     'result': 'Exec track handoff emailed %s' % day})
        sb('log_entries', {'person_id': p['id'], 'event': 'Exec track handoff',
                           'detail': 'Emailed to your work inbox %s with the connection note' % day, 'source': 'hark'})


def main():
    send = '--send' in sys.argv
    day = dt.datetime.now(TZ).date().isoformat()
    subject = SUBJECT % day
    ready, waiting = candidates()
    for p, why in waiting:
        print('rolls to next day: %s %s (%s): %s' % (p['id'], p.get('name'), p.get('company'), why))
    if not ready:
        print('nothing to hand off (%d waiting)' % len(waiting))
        return 0
    body = body_for(ready)
    print('Subject: %s\nFrom: owner@example.com\nTo: %s\n\n%s' % (subject, TO, body))
    if not send:
        print('[dry run] would hand off %d: %s' % (len(ready), ', '.join(p['id'] for p in ready)))
        return 0
    if sent_today(subject):
        left = [p for p in ready if p['id'] in set(ledger().get(day) or [])]
        if left:   # an earlier run sent today's email but stopped before marking: mark what that email carried
            mark(left, day)
        print('already sent today: %s; skipping (%d marked from today\'s email)' % (subject, len(left)))
        return 0
    ledger(day, [p['id'] for p in ready])
    print(gws('gmail', '+send', '--to', TO, '--subject', subject, '--body', body))
    mark(ready, day)
    print('handed off %d: %s' % (len(ready), ', '.join(p['id'] for p in ready)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
